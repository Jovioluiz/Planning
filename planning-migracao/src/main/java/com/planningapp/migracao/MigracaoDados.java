/**
 * Copia os dados do banco do Planning original para o banco desta versão.
 *
 * <ul>
 *   <li>O destino recebe o schema pelo Liquibase (o mesmo changelog do deploy) e precisa estar vazio: a migração
 *       roda uma vez, numa transação só. Se algo falhar, nada fica gravado.</li>
 *   <li>Os ids são mantidos (as colunas são {@code GENERATED BY DEFAULT AS IDENTITY}) e as sequências são
 *       ajustadas no fim, para os próximos inserts continuarem de onde a origem parou.</li>
 *   <li>As senhas continuam em BCrypt: o login desta versão as reconhece e regrava em PBKDF2 (ver
 *       {@code SenhaLegada}). Ninguém precisa trocar de senha.</li>
 * </ul>
 *
 * O que muda em cada tabela está nos métodos e no MIGRACAO.md.
 */
public final class MigracaoDados {

    /**
     * @param moderadorLegado quem modera a sala criada para as tarefas sem sala do original; nulo = o primeiro ADMIN
     * @param zona            fuso das colunas de data sem fuso desta versão ({@code criado_em}, {@code criada_em})
     * @param simular         faz tudo e desfaz no fim, só para ver o relatório
     */
    public record Opcoes(String moderadorLegado, ZoneId zona, boolean simular) {

        public static Opcoes padrao() {
            return new Opcoes(null, ZoneId.of("America/Sao_Paulo"), false);
        }
    }

    static final String NOME_SALA_LEGADO = "Backlog (migrado do Planning original)";

    private final Connection origem;
    private final Connection destino;
    private final Opcoes opcoes;
    private final Relatorio relatorio = new Relatorio();

    private final Set<Long> usuarios = new HashSet<>();
    private final Set<Long> salas = new HashSet<>();
    private final Map<Long, Long> salaDaTarefa = new HashMap<>();
    private final Map<Long, Instant> criacaoDaSala = new HashMap<>();

    private MigracaoDados(Connection origem, Connection destino, Opcoes opcoes) {
        this.origem = origem;
        this.destino = destino;
        this.opcoes = opcoes;
    }

    public static Relatorio migrar(Connection origem, Connection destino, Opcoes opcoes) throws Exception {
        return new MigracaoDados(origem, destino, opcoes).executar();
    }

    private Relatorio executar() throws Exception {
        Migracoes.aplicar(destino, MigracaoDados.class.getClassLoader());
        exigirDestinoVazio();

        boolean autoCommit = destino.getAutoCommit();
        destino.setAutoCommit(false);
        try {
            migrarUsuarios();
            migrarSalas();
            migrarTarefas();
            migrarEstimativas();
            migrarParticipantes();
            migrarMembros();
            contarDescartados();
            ajustarSequencias();
            if (opcoes.simular()) {
                destino.rollback();
                relatorio.avisar("SIMULAÇÃO: nada foi gravado no destino (rollback).");
            } else {
                destino.commit();
            }
            return relatorio;
        } catch (Exception e) {
            destino.rollback();
            throw e;
        } finally {
            destino.setAutoCommit(autoCommit);
        }
    }

    private void exigirDestinoVazio() throws SQLException {
        for (String tabela : List.of("usuarios", "salas", "tarefas")) {
            if (contar(destino, "SELECT COUNT(*) FROM " + tabela) > 0) {
                throw new IllegalStateException("O banco de destino já tem dados (tabela " + tabela + "). A migração"
                        + " só roda num banco vazio, para não misturar nem duplicar registros.");
            }
        }
    }

    /** {@code senha} (BCrypt) vai como está para {@code senha_hash}. O original não guardava a data de criação. */
    private void migrarUsuarios() throws SQLException {
        List<String> longos = new ArrayList<>();
        try (Statement sql = origem.createStatement();
             ResultSet rs = sql.executeQuery("SELECT id, usuario, senha, tipo_perfil FROM usuarios ORDER BY id");
             PreparedStatement insert = destino.prepareStatement(
                     "INSERT INTO usuarios (id, usuario, senha_hash, perfil, criado_em, ativo) VALUES (?, ?, ?, ?, ?, ?)")) {
            LocalDateTime agora = LocalDateTime.now(opcoes.zona());
            while (rs.next()) {
                String nome = rs.getString("usuario");
                if (nome.length() > 50) {
                    longos.add(nome);
                    continue;
                }
                long id = rs.getLong("id");
                insert.setLong(1, id);
                insert.setString(2, nome);
                insert.setString(3, rs.getString("senha"));
                insert.setString(4, rs.getString("tipo_perfil"));
                insert.setObject(5, agora);
                insert.setBoolean(6, true);
                insert.addBatch();
                usuarios.add(id);
            }
            if (!longos.isEmpty()) {
                throw new IllegalStateException("Usuários com mais de 50 caracteres (limite desta versão), renomeie na"
                        + " origem antes de migrar: " + longos);
            }
            insert.executeBatch();
        }
        relatorio.contar("usuarios", usuarios.size());
    }

    private void migrarSalas() throws SQLException {
        try (Statement sql = origem.createStatement();
             ResultSet rs = sql.executeQuery("SELECT id, nome, codigo, id_moderador, ativa, criada_em FROM salas ORDER BY id");
             PreparedStatement insert = insertSala()) {
            while (rs.next()) {
                long id = rs.getLong("id");
                Instant criada = instante(rs, "criada_em");
                inserirSala(insert, id, cortar(rs.getString("nome"), 100, "Sala " + id), rs.getString("codigo"),
                        rs.getLong("id_moderador"), rs.getBoolean("ativa"), criada);
            }
            insert.executeBatch();
        }
        relatorio.contar("salas", salas.size());
    }

    private PreparedStatement insertSala() throws SQLException {
        return destino.prepareStatement(
                "INSERT INTO salas (id, nome, codigo, id_moderador, ativa, criada_em) VALUES (?, ?, ?, ?, ?, ?)");
    }

    private void inserirSala(PreparedStatement insert, long id, String nome, String codigo, long moderador,
                             boolean ativa, Instant criada) throws SQLException {
        Instant quando = criada != null ? criada : Instant.now();
        insert.setLong(1, id);
        insert.setString(2, nome);
        insert.setString(3, codigo);
        insert.setLong(4, moderador);
        insert.setBoolean(5, ativa);
        insert.setObject(6, LocalDateTime.ofInstant(quando, opcoes.zona()));
        insert.addBatch();
        salas.add(id);
        criacaoDaSala.put(id, quando);
    }

    /**
     * Toda tarefa desta versão pertence a uma sala; as "legadas" do original (sem sala) vão para uma sala criada
     * para elas, moderada pelo ADMIN escolhido (ou o primeiro).
     */
    private void migrarTarefas() throws Exception {
        Long salaLegado = null;
        if (contar(origem, "SELECT COUNT(*) FROM tarefas WHERE id_sala IS NULL") > 0) {
            salaLegado = criarSalaLegado();
        }

        Set<String> numerosPorSala = new HashSet<>();
        int liberadas = 0;
        Map<Long, Integer> liberadasPorSala = new HashMap<>();
        try (Statement sql = origem.createStatement();
             ResultSet rs = sql.executeQuery("SELECT * FROM tarefas ORDER BY id");
             PreparedStatement insert = destino.prepareStatement("""
                     INSERT INTO tarefas (id, numero, titulo, descricao, sprint, status, fase, fase_horas_teste,
                         rodada_atual, pontos_finais, horas_finais, horas_teste_finais, liberada_em, encerrada_em,
                         horas_liberadas_em, dados_extras, id_sala)
                     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)""")) {
            while (rs.next()) {
                long id = rs.getLong("id");
                Long sala = (Long) rs.getObject("id_sala", Long.class);
                long salaId = sala != null ? sala : salaLegado;
                String numero = rs.getObject("numero") != null ? String.valueOf(rs.getLong("numero")) : "SEM-NUMERO-" + id;
                if (!numerosPorSala.add(salaId + "|" + numero)) {
                    relatorio.avisar("Tarefa " + id + " ignorada: número " + numero + " repetido na sala " + salaId);
                    continue;
                }
                EstadoTarefa estado = EstadoTarefa.de(rs.getBoolean("liberada"), rs.getBoolean("estimada"),
                        rs.getBoolean("pulada"), rs.getBoolean("pontos_revelados"), rs.getBoolean("horas_liberadas"),
                        rs.getBoolean("horas_reveladas"), rs.getBoolean("horas_teste_liberadas"),
                        rs.getBoolean("horas_teste_reveladas"));
                if ("LIBERADA".equals(estado.status())) {
                    liberadas++;
                    liberadasPorSala.merge(salaId, 1, Integer::sum);
                }
                Integer rodada = (Integer) rs.getObject("rodada_atual", Integer.class);

                insert.setLong(1, id);
                insert.setString(2, numero);
                insert.setString(3, cortar(rs.getString("titulo"), 255, "(sem título)"));
                insert.setString(4, rs.getString("descricao"));
                insert.setString(5, cortarAvisando(rs.getString("sprint"), 50, "sprint da tarefa " + id));
                insert.setString(6, estado.status());
                insert.setString(7, estado.fase());
                insert.setString(8, estado.faseHorasTeste());
                insert.setInt(9, rodada != null && rodada > 0 ? rodada : 1);
                setInteiro(insert, 10, rs.getObject("pontos_finais"));
                setInteiro(insert, 11, rs.getObject("horas_finais"));
                setInteiro(insert, 12, rs.getObject("horas_teste_finais"));
                setInstante(insert, 13, instante(rs, "liberada_em"));
                setInstante(insert, 14, "PULADA".equals(estado.status()) || "ESTIMADA".equals(estado.status())
                        ? instante(rs, "estimada_em") : null);
                setInstante(insert, 15, instante(rs, "horas_liberadas_em"));
                insert.setString(16, dadosExtras(id, rs.getString("dados_extras"), rs.getObject("prioridade"),
                        rs.getString("status")));
                insert.setLong(17, salaId);
                insert.addBatch();
                salaDaTarefa.put(id, salaId);
            }
            insert.executeBatch();
        }
        liberadasPorSala.forEach((sala, n) -> {
            if (n > 1) {
                relatorio.avisar("A sala " + sala + " tem " + n + " tarefas em votação (esta versão permite uma por vez;"
                        + " finalize ou pule as extras)");
            }
        });
        relatorio.contar("tarefas", salaDaTarefa.size());
        relatorio.contar("tarefas em votação", liberadas);
    }

    private long criarSalaLegado() throws SQLException {
        long moderador = moderadorDoLegado();
        long id = contar(origem, "SELECT COALESCE(MAX(id), 0) FROM salas") + 1;
        try (PreparedStatement insert = insertSala()) {
            inserirSala(insert, id, NOME_SALA_LEGADO, UUID.randomUUID().toString(), moderador, true, Instant.now());
            insert.executeBatch();
        }
        relatorio.contar("salas", 1);
        relatorio.avisar("Tarefas sem sala (backlog legado) foram para a sala nova \"" + NOME_SALA_LEGADO + "\" (id " + id
                + "), moderada pelo usuário de id " + moderador);
        return id;
    }

    private long moderadorDoLegado() throws SQLException {
        String filtro = opcoes.moderadorLegado() != null
                ? "usuario = ? AND tipo_perfil = 'ADMIN'"
                : "tipo_perfil = 'ADMIN'";
        try (PreparedStatement sql = origem.prepareStatement("SELECT id FROM usuarios WHERE " + filtro + " ORDER BY id")) {
            if (opcoes.moderadorLegado() != null) {
                sql.setString(1, opcoes.moderadorLegado());
            }
            try (ResultSet rs = sql.executeQuery()) {
                if (rs.next()) {
                    return rs.getLong(1);
                }
            }
        }
        throw new IllegalStateException("Há tarefas sem sala, mas nenhum ADMIN"
                + (opcoes.moderadorLegado() != null ? " chamado " + opcoes.moderadorLegado() : "")
                + " para moderar a sala que vai recebê-las. Use --moderador-legado=USUARIO");
    }

    /**
     * Horas em {@code Double} viram inteiro (arredondado): os votos eram de 1 a 16 sempre inteiros. Se houver mais
     * de um voto do mesmo usuário na mesma rodada (o original não impedia nas horas), fica o mais recente.
     */
    private void migrarEstimativas() throws SQLException {
        Map<String, Object[]> porChave = new LinkedHashMap<>();
        int orfas = 0;
        int repetidas = 0;
        try (Statement sql = origem.createStatement();
             ResultSet rs = sql.executeQuery("""
                     SELECT id, id_tarefas, id_usuario, rodada, pontos, horas, horas_teste, votado_em_pontos, votado_em_horas
                     FROM estimativas ORDER BY id""")) {
            while (rs.next()) {
                long tarefa = rs.getLong("id_tarefas");
                long usuario = rs.getLong("id_usuario");
                if (!salaDaTarefa.containsKey(tarefa) || !usuarios.contains(usuario)) {
                    orfas++;
                    continue;
                }
                Integer rodada = (Integer) rs.getObject("rodada", Integer.class);
                int r = rodada != null && rodada > 0 ? rodada : 1;
                Object[] linha = {rs.getLong("id"), tarefa, usuario, r, rs.getObject("pontos"), rs.getObject("horas"),
                        rs.getObject("horas_teste"), instante(rs, "votado_em_pontos"), instante(rs, "votado_em_horas")};
                if (porChave.put(tarefa + "|" + usuario + "|" + r, linha) != null) {
                    repetidas++;
                }
            }
        }
        try (PreparedStatement insert = destino.prepareStatement("""
                INSERT INTO estimativas (id, id_tarefa, id_usuario, rodada, pontos, horas, horas_teste,
                    votado_em_pontos, votado_em_horas) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)""")) {
            for (Object[] l : porChave.values()) {
                insert.setLong(1, (Long) l[0]);
                insert.setLong(2, (Long) l[1]);
                insert.setLong(3, (Long) l[2]);
                insert.setInt(4, (Integer) l[3]);
                setInteiro(insert, 5, l[4]);
                setInteiro(insert, 6, l[5]);
                setInteiro(insert, 7, l[6]);
                setInstante(insert, 8, (Instant) l[7]);
                setInstante(insert, 9, (Instant) l[8]);
                insert.addBatch();
            }
            insert.executeBatch();
        }
        relatorio.contar("estimativas", porChave.size());
        if (orfas > 0) {
            relatorio.avisar(orfas + " voto(s) ignorado(s): a tarefa ou o usuário não existe mais na origem");
        }
        if (repetidas > 0) {
            relatorio.avisar(repetidas + " voto(s) repetido(s) do mesmo usuário na mesma rodada: ficou o mais recente");
        }
    }

    /** No original o {@code task_id} não tinha FK; vínculos com tarefas que já não existem ficam de fora. */
    private void migrarParticipantes() throws SQLException {
        int migrados = 0;
        int orfaos = 0;
        Set<String> vistos = new HashSet<>();
        try (Statement sql = origem.createStatement();
             ResultSet rs = sql.executeQuery("SELECT task_id, id_usuario FROM task_participants ORDER BY id");
             PreparedStatement insert = destino.prepareStatement(
                     "INSERT INTO participantes_tarefa (id_tarefa, id_usuario) VALUES (?, ?)")) {
            while (rs.next()) {
                long tarefa = rs.getLong("task_id");
                long usuario = rs.getLong("id_usuario");
                if (!salaDaTarefa.containsKey(tarefa) || !usuarios.contains(usuario)) {
                    orfaos++;
                    continue;
                }
                if (vistos.add(tarefa + "|" + usuario)) {
                    insert.setLong(1, tarefa);
                    insert.setLong(2, usuario);
                    insert.addBatch();
                    migrados++;
                }
            }
            insert.executeBatch();
        }
        relatorio.contar("participantes_tarefa", migrados);
        if (orfaos > 0) {
            relatorio.avisar(orfaos + " participante(s) ignorado(s): a tarefa ou o usuário não existe mais na origem");
        }
    }

    /** O original não guardava quando a pessoa entrou: fica a data de criação da sala. */
    private void migrarMembros() throws SQLException {
        int migrados = 0;
        try (Statement sql = origem.createStatement();
             ResultSet rs = sql.executeQuery("SELECT id_sala, id_usuario FROM sala_membros ORDER BY id");
             PreparedStatement insert = destino.prepareStatement(
                     "INSERT INTO sala_membros (id_sala, id_usuario, entrou_em) VALUES (?, ?, ?)")) {
            while (rs.next()) {
                long sala = rs.getLong("id_sala");
                long usuario = rs.getLong("id_usuario");
                if (!salas.contains(sala) || !usuarios.contains(usuario)) {
                    continue;
                }
                insert.setLong(1, sala);
                insert.setLong(2, usuario);
                setInstante(insert, 3, criacaoDaSala.get(sala));
                insert.addBatch();
                migrados++;
            }
            insert.executeBatch();
        }
        relatorio.contar("sala_membros", migrados);
    }

    /** {@code user_sprints} (seleção de sprint) não existe nesta versão; a tela já não era usada no original. */
    private void contarDescartados() throws SQLException {
        long sprints = contar(origem, "SELECT COUNT(*) FROM user_sprints");
        if (sprints > 0) {
            relatorio.avisar(sprints + " registro(s) de user_sprints não foram migrados (a seleção de sprint por"
                    + " usuário não existe nesta versão)");
        }
    }

    private void ajustarSequencias() throws SQLException {
        boolean postgres = destino.getMetaData().getDatabaseProductName().toLowerCase().contains("postgres");
        for (String tabela : List.of("usuarios", "salas", "tarefas", "estimativas", "participantes_tarefa", "sala_membros")) {
            long proximo = contar(destino, "SELECT COALESCE(MAX(id), 0) + 1 FROM " + tabela);
            try (Statement sql = destino.createStatement()) {
                if (postgres) {
                    sql.execute("SELECT setval(pg_get_serial_sequence('" + tabela + "', 'id'), " + proximo + ", false)");
                } else {
                    sql.execute("ALTER TABLE " + tabela + " ALTER COLUMN id RESTART WITH " + proximo);
                }
            }
        }
    }

    /**
     * Junta {@code prioridade} e {@code status} (campos do original sem equivalente aqui) às colunas extras, para
     * não perder a informação. Um JSON inválido na origem é descartado com aviso.
     */
    private String dadosExtras(long tarefa, String json, Object prioridade, String status) {
        JsonObjectBuilder extras = Json.createObjectBuilder();
        if (json != null && !json.isBlank()) {
            try (JsonReader leitor = Json.createReader(new StringReader(json))) {
                JsonObject objeto = leitor.readObject();
                objeto.forEach(extras::add);
            } catch (RuntimeException e) {
                relatorio.avisar("Tarefa " + tarefa + ": dados_extras não é um JSON de objeto válido e foi descartado");
            }
        }
        JsonObject parcial = extras.build();
        JsonObjectBuilder completo = Json.createObjectBuilder(parcial);
        if (prioridade != null && !temColuna(parcial, "prioridade")) {
            completo.add("prioridade", String.valueOf(prioridade));
        }
        if (status != null && !status.isBlank() && !temColuna(parcial, "status")) {
            completo.add("status", status);
        }
        JsonObject resultado = completo.build();
        return resultado.isEmpty() ? null : resultado.toString();
    }

    /** O CSV do original pode ter "Prioridade", "PRIORIDADE"...: não duplica a coluna com outra caixa. */
    private static boolean temColuna(JsonObject extras, String coluna) {
        return extras.keySet().stream().anyMatch(c -> c.equalsIgnoreCase(coluna));
    }

    private String cortarAvisando(String valor, int limite, String descricao) {
        if (valor != null && valor.length() > limite) {
            relatorio.avisar("O valor de " + descricao + " tinha mais de " + limite + " caracteres e foi cortado");
            return valor.substring(0, limite);
        }
        return valor;
    }

    private String cortar(String valor, int limite, String seVazio) {
        if (valor == null || valor.isBlank()) {
            return seVazio;
        }
        return cortarAvisando(valor, limite, "\"" + valor.substring(0, Math.min(30, valor.length())) + "...\"");
    }

    private static Instant instante(ResultSet rs, String coluna) throws SQLException {
        Timestamp valor = rs.getTimestamp(coluna);
        return valor != null ? valor.toInstant() : null;
    }

    private static void setInstante(PreparedStatement sql, int indice, Instant valor) throws SQLException {
        if (valor == null) {
            sql.setNull(indice, Types.TIMESTAMP_WITH_TIMEZONE);
        } else {
            sql.setObject(indice, OffsetDateTime.ofInstant(valor, ZoneOffset.UTC));
        }
    }

    /** Valores {@code Double} do original (horas) são arredondados. */
    private static void setInteiro(PreparedStatement sql, int indice, Object valor) throws SQLException {
        if (valor == null) {
            sql.setNull(indice, Types.INTEGER);
        } else {
            sql.setInt(indice, (int) Math.round(((Number) valor).doubleValue()));
        }
    }

    private static long contar(Connection conexao, String consulta) throws SQLException {
        try (Statement sql = conexao.createStatement(); ResultSet rs = sql.executeQuery(consulta)) {
            rs.next();
            return rs.getLong(1);
        }
    }
}
