-- Schema do Planning original (Spring Boot 3.2 + Hibernate 6, ddl-auto=update), com os nomes que o Spring gera
-- (camelCase -> snake_case) e os tipos equivalentes no H2. Instant -> TIMESTAMP WITH TIME ZONE, Double -> FLOAT(53).

CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario VARCHAR(255) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    tipo_perfil VARCHAR(255) NOT NULL
);

CREATE TABLE salas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    codigo VARCHAR(255) NOT NULL UNIQUE,
    id_moderador BIGINT NOT NULL REFERENCES usuarios (id),
    ativa BOOLEAN NOT NULL,
    criada_em TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE tarefas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero BIGINT,
    titulo VARCHAR(255),
    descricao VARCHAR(255),
    prioridade INTEGER,
    status VARCHAR(255),
    estimada BOOLEAN NOT NULL,
    liberada BOOLEAN NOT NULL,
    pontos_revelados BOOLEAN NOT NULL,
    horas_reveladas BOOLEAN NOT NULL,
    horas_liberadas BOOLEAN NOT NULL,
    horas_teste_liberadas BOOLEAN NOT NULL,
    horas_teste_reveladas BOOLEAN NOT NULL,
    sprint VARCHAR(255),
    liberada_em TIMESTAMP(6) WITH TIME ZONE,
    horas_liberadas_em TIMESTAMP(6) WITH TIME ZONE,
    horas_teste_liberadas_em TIMESTAMP(6) WITH TIME ZONE,
    estimada_em TIMESTAMP(6) WITH TIME ZONE,
    rodada_atual INTEGER,
    pontos_finais INTEGER,
    horas_finais FLOAT(53),
    horas_teste_finais FLOAT(53),
    pulada BOOLEAN DEFAULT FALSE,
    dados_extras VARCHAR(100000),
    id_sala BIGINT REFERENCES salas (id)
);

CREATE TABLE estimativas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tarefas BIGINT NOT NULL REFERENCES tarefas (id),
    id_usuario BIGINT NOT NULL REFERENCES usuarios (id),
    pontos INTEGER,
    revelada BOOLEAN NOT NULL,
    horas FLOAT(53),
    horas_reveladas BOOLEAN,
    rodada INTEGER,
    votado_em_pontos TIMESTAMP(6) WITH TIME ZONE,
    votado_em_horas TIMESTAMP(6) WITH TIME ZONE,
    horas_teste FLOAT(53),
    horas_teste_reveladas BOOLEAN
);

-- task_id sem FK, como no original
CREATE TABLE task_participants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL,
    id_usuario BIGINT NOT NULL REFERENCES usuarios (id),
    UNIQUE (task_id, id_usuario)
);

CREATE TABLE sala_membros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sala BIGINT NOT NULL REFERENCES salas (id),
    id_usuario BIGINT NOT NULL REFERENCES usuarios (id),
    UNIQUE (id_sala, id_usuario)
);

CREATE TABLE user_sprints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES usuarios (id),
    sprint VARCHAR(255),
    UNIQUE (id_usuario, sprint)
);

